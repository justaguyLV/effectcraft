def escape(text):
    return (text.replace("&", "&amp;").replace("<", "&lt;").replace("'", "\\'").replace('"', '\\"'))


def positional(text):
    """%d/%d -> %1$d/%2$d when a string has several plain placeholders (same order, same meaning)."""
    pattern = re.compile(r"%(?!\d+\$)([-#+ 0,(]*\d*(?:\.\d+)?[a-zA-Z])")
    if len(pattern.findall(text)) < 2:
        return text
    counter = iter(range(1, 100))
    return pattern.sub(lambda m: "%" + str(next(counter)) + "$" + m.group(1), text)


def parse(path):
    data = {}
    try:
        text = open(path, encoding="utf-8").read()
    except FileNotFoundError:
        return data
    for m in re.finditer(r'<string name="([^"]+)"([^>]*)>(.*?)</string>', text, re.S):
        if 'translatable="false"' not in m.group(2):
            data[m.group(1)] = m.group(3)
    return data


def placeholders(text):
    return sorted(re.findall(r"%(?:\d+\$)?[-#+ 0,(]*\d*(?:\.\d+)?[a-zA-Z]", text))


en = parse(res + "/values/strings.xml")

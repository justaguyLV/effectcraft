lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
written = skipped = 0
for key, value in AR.items():
    if key not in en or key in have:
        skipped += 1
        continue
    if placeholders(en[key]) != placeholders(value):
        print(f"placeholder mismatch, kept English: {key}: {placeholders(en[key])} vs {placeholders(value)}")
        continue
    value = positional(value)
    lines.append(f'    <string name="{key}">{escape(value)}</string>')
    written += 1
lines.append("</resources>")
open(res + "/values-ar/blockcomet_translations.xml", "w", encoding="utf-8").write("\n".join(lines) + "\n")
